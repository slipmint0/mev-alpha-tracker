// scripts/verifyContract.js
import { ethers } from "ethers";

const RPC_URL = "https://arb1.arbitrum.io/rpc";
const targetAddress = (typeof process !== "undefined" && process.argv?.[2]) || "0x92c70a2fe1274ee258a0fb7dbff5f89bb2e4bbf9";

async function verifyContractOnArbitrum() {
  const provider = new ethers.JsonRpcProvider(RPC_URL);

  console.log(`Checking address on Arbitrum One (Chain ID 42161): ${targetAddress}`);
  try {
    const code = await provider.getCode(targetAddress);
    if (code === "0x") {
      console.log("❌ RESULT: NO CONTRACT FOUND ON ARBITRUM ONE");
      console.log("Explanation: This address was generated by Remix VM (browser simulator), not the live Arbitrum network.");
      console.log("Next Action: Switch Remix Environment to 'Injected Provider - MetaMask' and click Deploy.");
      return false;
    } else {
      console.log("✅ RESULT: VALID CONTRACT FOUND ON ARBITRUM ONE!");
      console.log(`Bytecode length: ${code.length} bytes`);
      return true;
    }
  } catch (error) {
    console.error("RPC Error:", error.message || error);
    return false;
  }
}

verifyContractOnArbitrum();
